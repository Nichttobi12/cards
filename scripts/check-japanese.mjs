assert.equal(nameScore('ピカチュウ','Glurak'),Infinity);
assert.equal(cardDisplayName({name:'メガゲンガーex'},'ja'),'Mega Gengar ex');
assert.equal(cardDisplayName({name:'Glurak'},'de'),'Glurak');
assert.equal(parseCardQuery('０２５／１６５').number,'025');
assert.equal(parseCardQuery('SV-P-001').id,'SV-P-001');
assert.equal(parseCardQuery('001/SV-P').set,'SV-P');
assert.equal(parseCardQuery('SV-P 001').set,'SV-P');
