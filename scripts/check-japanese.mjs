assert.equal((await searchCards('Glurak 201/165','ja','',false))[0].id,'SV2a-201');
assert.equal((await searchCards('Pikachu','ja','SV2A',false))[0].id,'SV2a-025');
assert.equal((await searchCards('Mega Gengar','ja','M2a',false))[0].id,'M2a-220');
