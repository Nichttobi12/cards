import {strict as assert} from 'node:assert';
import {build} from 'esbuild';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const dir=await mkdtemp(join(tmpdir(),'japanese-catalog-'));
for(const name of ['search','catalog','variants','graded-prices','japanese-names'])await build({entryPoints:['supabase/functions/pokevault/'+name+'.ts'],bundle:true,platform:'node',format:'esm',outfile:join(dir,name+'.mjs')});
await build({entryPoints:['src/scan-text.ts'],bundle:true,platform:'node',format:'esm',outfile:join(dir,'scan.mjs')});
const {normalize,nameScore,cardMatches,parseCardQuery}=await import(join(dir,'search.mjs'));
const {cardDisplayName}=await import(join(dir,'japanese-names.mjs'));
